const normalizeSearch = (value) => String(value || '')
    .toLocaleLowerCase('uk-UA')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[ʼ’`]/g, "'")
    .trim()

const emojiMatchesSearch = (emoji, category, categoryIndex, term) => {
    const keywords = [
        emoji,
        category.label,
        category.name,
        ...(CATEGORY_KEYWORDS[categoryIndex] || []),
        ...(EMOJI_KEYWORDS[emoji] || [])
    ]
    return normalizeSearch(keywords.join(' ')).includes(term)
}

function EmojiPicker({ onSelect, onClose, anchorRef }) {
    const [search, setSearch] = useState('')
    const [activeCategory, setActiveCategory] = useState(0)
    const pickerRef = useRef(null)

    // Закриваємо пікер по кліку поза ним
    useEffect(() => {
        const handleClickOutside = (e) => {
            const insidePicker = pickerRef.current && pickerRef.current.contains(e.target)
            const insideAnchor = anchorRef?.current && anchorRef.current.contains(e.target)
            if (!insidePicker && !insideAnchor) {
                onClose && onClose()
            }
        }
        document.addEventListener('mousedown', handleClickOutside)
        return () => document.removeEventListener('mousedown', handleClickOutside)
    }, [anchorRef, onClose])

    // Фільтрація за пошуком
    const searchTerm = normalizeSearch(search)
    const searchResults = searchTerm
        ? EMOJI_CATEGORIES.flatMap((category, categoryIndex) =>
            category.emojis
                .filter(emoji => emojiMatchesSearch(emoji, category, categoryIndex, searchTerm))
                .map(emoji => ({ emoji, categoryIndex }))
        ).filter((entry, index, entries) =>
            entries.findIndex(item => item.emoji === entry.emoji) === index
        ).map(entry => entry.emoji)
        : null

    return (
        <FloatingPanel
            open
            anchorRef={anchorRef}
            panelRef={pickerRef}
            className="emoji-picker"
            align="right"
            width={380}
            maxHeight={360}
            zIndex={11000}
        >
            {/* Пошук */}
            <div className="emoji-search-wrap">
                <input
                    className="emoji-search"
                    placeholder="🔍 Пошук..."
                    value={search}
                    onChange={e => setSearch(e.target.value)}
                    autoFocus
                />
            </div>

            {/* Категорії */}
            {!search && (
                <div className="emoji-categories">
                    {EMOJI_CATEGORIES.map((cat, i) => (
                        <button
                            key={i}
                            className={`emoji-cat-btn ${activeCategory === i ? 'active' : ''}`}
                            onClick={() => setActiveCategory(i)}
                            title={cat.name}
                        >
                            {cat.label}
                        </button>
                    ))}
                </div>
            )}

            {/* Сітка з емодзі */}
            <div className="emoji-grid">
                {(searchResults || EMOJI_CATEGORIES[activeCategory].emojis).map((emoji, i) => (
                    <button
                        key={i}
                        className="emoji-btn"
                        onClick={() => onSelect(emoji)}
                        title={emoji}
                    >
                        {emoji}
                    </button>
                ))}
                {searchResults && searchResults.length === 0 && (
                    <div style={{ padding: '20px', color: 'var(--text-secondary)', gridColumn: '1/-1', textAlign: 'center' }}>
                        Нічого не знайдено
                    </div>
                )}
            </div>
        </FloatingPanel>
    )
}

export default EmojiPicker
